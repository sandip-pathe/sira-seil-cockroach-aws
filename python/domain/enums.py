class StackRisk(StringEnum):
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"

    @property
    def rank(self) -> int:
        return {
            StackRisk.LOW: 0,
            StackRisk.MEDIUM: 1,
            StackRisk.HIGH: 2,
            StackRisk.CRITICAL: 3,
        }[self]


